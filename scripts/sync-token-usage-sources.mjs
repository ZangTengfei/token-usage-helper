import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const normalizeNewlines = value => value.replace(/\r\n/g, '\n');
const sources = JSON.parse(await readFile(new URL('../sources.json', import.meta.url)));
assert.equal(new Set(sources.map(s=>s.id)).size, sources.length);
for (const s of sources) {
  assert.match(s.id, /^[a-z][a-z0-9-]*$/);
  assert.ok(s.label && ['tokscale','local-v1','csv'].includes(s.adapter));
  assert.equal(typeof s.defaultEnabled, 'boolean');
}
const header = '// Generated by scripts/sync-token-usage-sources.mjs; edit sources.json.\n';
const js = header + `export const SOURCES = ${JSON.stringify(sources, null, 2)};\nexport const CLIENTS = Object.fromEntries(SOURCES.map(s => [s.id, s.label]));\nexport const DEFAULT_CLIENTS = SOURCES.filter(s => s.defaultEnabled).map(s => s.id);\nexport const LOCAL_CLIENTS = SOURCES.filter(s => s.adapter === 'local-v1').map(s => s.id);\n`;
const ids=sources.map(s=>s.id);
const rust = header + `#[rustfmt::skip]\npub const CLIENTS: [&str; ${ids.length}] = [${ids.map(JSON.stringify).join(',')}];\n#[rustfmt::skip]\npub const DEFAULT_CLIENTS: &[&str] = &[${sources.filter(s=>s.defaultEnabled).map(s=>JSON.stringify(s.id)).join(',')}];\n#[rustfmt::skip]\npub const LOCAL_CLIENTS: &[&str] = &[${sources.filter(s=>s.adapter==='local-v1').map(s=>JSON.stringify(s.id)).join(',')}];\n`;
for (const [path,content] of [
  ['desktop/token-usage/renderer/source-catalog.mjs',js],
  ['desktop/token-usage-tauri/src-tauri/src/source_catalog.rs',rust],
]) {
  const file=new URL('../'+path,import.meta.url);
  if(process.argv.includes('--check')) assert.equal(normalizeNewlines(await readFile(file,'utf8')),content,`Regenerate ${path}`);
  else await writeFile(file,content);
}
console.log('PASS usage source catalog: '+sources.length+' sources');

const helper = new URL('../public/tools/club-usage.mjs', import.meta.url);
const block = `// BEGIN GENERATED USAGE SOURCES
// prettier-ignore
export const SUPPORTED_CLIENTS = ${JSON.stringify(sources.filter(s=>s.adapter!=='csv').map(s=>s.id))};
// prettier-ignore
export const DEFAULT_CLIENTS = ${JSON.stringify(sources.filter(s=>s.defaultEnabled).map(s=>s.id))};
// prettier-ignore
const LOCAL_CLIENTS = ${JSON.stringify(sources.filter(s=>s.adapter==='local-v1').map(s=>s.id))};
// END GENERATED USAGE SOURCES`;
const helperSource = normalizeNewlines(await readFile(helper, 'utf8'));
const nextHelper = helperSource.replace(/\/\/ BEGIN GENERATED USAGE SOURCES[\s\S]*?\/\/ END GENERATED USAGE SOURCES/, block);
if(process.argv.includes('--check')) assert.equal(helperSource, nextHelper, 'Regenerate the standalone helper source list.');
else await writeFile(helper, nextHelper);
